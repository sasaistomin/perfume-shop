// зберігаємо регістр першої літери: «Троянда» → «Роза»
const keepCase = (src, out) => (src[0] && src[0] === src[0].toUpperCase() ? out[0].toUpperCase() + out.slice(1) : out);
const dictKey = (s) => s.trim().toLowerCase().replace(/[’ʼ`]/g, "'");
const DICT_N = Object.fromEntries(Object.entries(DICT).map(([k, v]) => [dictKey(k), v]));

export function fromDict(text) {
  const s = String(text || '').trim();
  const hit = DICT_N[dictKey(s)];
  return hit ? keepCase(s, hit) : null;
}

const needsTranslation = (s) => typeof s === 'string' && CYR_UK.test(s);
const cache = new Map();

async function withTimeout(promise, ms) {
  let timer;
  return Promise.race([promise, new Promise((_, rej) => (timer = setTimeout(() => rej(new Error('timeout')), ms)))]).finally(() =>
    clearTimeout(timer),
  );
}

async function deepl(texts) {
  const key = process.env.DEEPL_API_KEY;
  if (!key) return null;
  const host = key.endsWith(':fx') ? 'https://api-free.deepl.com' : 'https://api.deepl.com';
  const r = await withTimeout(
    fetch(`${host}/v2/translate`, {
      method: 'POST',
      headers: { Authorization: `DeepL-Auth-Key ${key}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ text: texts, source_lang: 'UK', target_lang: 'RU' }),
    }),
    8000,
  );
  if (!r.ok) throw new Error(`DeepL ${r.status}`);
  const d = await r.json();
  return d.translations.map((t) => t.text);
}

async function google(text) {
  const url =
    (process.env.GOOGLE_TRANSLATE_URL || 'https://translate.googleapis.com/translate_a/single') +
    `?client=gtx&sl=uk&tl=ru&dt=t&q=${encodeURIComponent(text)}`;
  const r = await withTimeout(fetch(url), 6000);
  if (!r.ok) throw new Error(`Google ${r.status}`);
  const d = await r.json();
  return (d[0] || []).map((x) => x[0]).join('');
}

// Перекладає масив рядків. Повертає масив того ж розміру; null — не вдалося перекласти.
export async function translateMany(texts) {
  const out = texts.map((t) => {
    if (!needsTranslation(t)) return t || '';
    return fromDict(t) ?? cache.get(t) ?? undefined;
  });
  const todo = [...new Set(texts.filter((t, i) => out[i] === undefined))];
  if (todo.length) {
    let result = null;
    try {
      result = await deepl(todo);
    } catch (e) {
      console.warn('[translate] DeepL:', e.message);
    }
    if (!result) {
      result = [];
      for (const t of todo) {
        try {
          result.push(await google(t));
        } catch (e) {
          console.warn('[translate] Google:', e.message);
          result.push(null);
        }
      }
    }
    todo.forEach((t, i) => result[i] && cache.set(t, result[i]));
  }
  return out.map((v, i) => (v === undefined ? (cache.get(texts[i]) ?? null) : v));
}

/* ------------------------------------------------------------ переклад товару */

// Поля товару, які перекладаються: [ключ, як прочитати український текст, як прочитати/записати російський].
function slots(p) {
  p.ru ??= { name: '', description: '', category: '' };
  p.ru.terms ??= {};
  p.perfumer ??= { name: '', title: '', bio: '', photo: '' };
  const list = [
    ['name', () => p.name, () => p.ru.name, (v) => (p.ru.name = v)],
    ['description', () => p.description, () => p.ru.description, (v) => (p.ru.description = v)],
    ['category', () => p.category, () => p.ru.category, (v) => (p.ru.category = v)],
    ['perfumer.title', () => p.perfumer.title, () => p.perfumer.titleRu, (v) => (p.perfumer.titleRu = v)],
    ['perfumer.bio', () => p.perfumer.bio, () => p.perfumer.bioRu, (v) => (p.perfumer.bioRu = v)],
  ];
  for (const g of ['top', 'heart', 'base']) {
    for (const n of p.notes?.[g] || []) {
      list.push([`note:${n.name}`, () => n.name, () => n.nameRu, (v) => (n.nameRu = v)]);
    }
  }
  // теги та тип показуються як окремі слова: зберігаємо їх у словничку товару ru.terms
  for (const word of [...new Set([...(p.tags || []), p.type].filter(Boolean))]) {
    list.push([`term:${word}`, () => word, () => p.ru.terms[word], (v) => (v ? (p.ru.terms[word] = v) : delete p.ru.terms[word])]);
  }
  return list;
}

// Що треба перекласти: поле порожнє, або воно було перекладене автоматично, а український текст змінився.
// Те, що ви виправили в адмінці вручну, не перезаписується.
function plan(p) {
  p.ruAuto ??= {};
  const jobs = [];
  for (const [key, getSrc, getRu, setRu] of slots(p)) {
    const src = String(getSrc() || '').trim();
    const cur = String(getRu() || '').trim();
    const auto = p.ruAuto[key];
    if (!needsTranslation(src)) {
      if (auto && cur === auto.out) setRu('');
      delete p.ruAuto[key];
      continue;
    }
    const wasAuto = auto && cur === auto.out;
    if (cur && !wasAuto) continue; // ручний переклад
    if (wasAuto && auto.src === src) continue; // уже актуальний
    jobs.push({ key, src, setRu });
  }
  // прибираємо записи про поля, яких більше немає
  const alive = new Set(slots(p).map((s) => s[0]));
  for (const k of Object.keys(p.ruAuto)) if (!alive.has(k)) delete p.ruAuto[k];
  return jobs;
}

export function needsRu(p) {
  return plan(structuredClone(p)).length > 0;
}

// Перекладає товар (змінює об'єкт). Повертає кількість перекладених полів.
export async function translateProduct(p) {
  const jobs = plan(p);
  if (!jobs.length) return 0;
  const res = await translateMany(jobs.map((j) => j.src));
  let done = 0;
  jobs.forEach((j, i) => {
    if (!res[i]) return;
    j.setRu(res[i]);
    p.ruAuto[j.key] = { src: j.src, out: res[i] };
    done++;
  });
  return done;
}

// Копіює переклади з підготовленого товару в той, що лежить у базі (якщо український текст не змінився за цей час).
export function applyRu(target, translated) {
  const src = new Map(slots(translated).map(([k, getSrc, getRu]) => [k, { src: getSrc(), ru: getRu() }]));
  target.ruAuto ??= {};
  for (const [key, getSrc, getRu, setRu] of slots(target)) {
    const a = translated.ruAuto?.[key];
    const s = src.get(key);
    if (!a || !s || String(getSrc() || '').trim() !== a.src) continue;
    const cur = String(getRu() || '').trim();
    const old = target.ruAuto[key];
    if (cur && !(old && cur === old.out)) continue; // ручний переклад не чіпаємо
    setRu(a.out);
    target.ruAuto[key] = a;
  }
}
